import { useEffect, useState } from 'react'
import { мойПрофиль, выйти } from './api'
import type { Пользователь } from './api'
import Вход from './Vhod'
import Профиль from './Profil'
import './App.css'

export default function App() {
  const [кто, установитьКто] = useState<Пользователь | null>(null)
  const [проверяем, установитьПроверяем] = useState(true)

  // Кука сессии живёт и после перезагрузки страницы, поэтому при запуске
  // спрашиваем сервер, вошли мы уже или нет. 403 здесь — не поломка, а
  // обычный ответ «ты аноним», так что просто показываем форму входа.
  useEffect(() => {
    мойПрофиль()
      .then(установитьКто)
      .catch(() => установитьКто(null))
      .finally(() => установитьПроверяем(false))
  }, [])

  const выход = async () => {
    try {
      await выйти()
    } finally {
      установитьКто(null)
    }
  }

  return (
    <div className="страница">
      <header>
        <h1>Рок-группа</h1>
        <p className="слоган">Личный кабинет музыканта</p>
      </header>

      <main>
        {проверяем ? (
          <p className="ждём">Проверяем, вошли ли вы…</p>
        ) : кто ? (
          <Профиль кто={кто} приОбновлении={установитьКто} приВыходе={выход} />
        ) : (
          <Вход приВходе={установитьКто} />
        )}
      </main>

      <footer>
        <p>Жунусов Аазам · группа АИН-1-25 · Веб-технологии, ДЗ8</p>
      </footer>
    </div>
  )
}
